import { argv, exit, env } from 'node:process';
import { exec, execFile } from 'node:child_process';
import { promisify } from 'node:util';

const execAsync = promisify(exec);

/**
 * psql aufrufen, ohne Shell und ohne die SQL zu verstuemmeln.
 *
 * Vorher stand hier:
 *   execAsync(`psql "${databaseUrl}" -c "${sql.replace(/\n/g, ' ')}"`)
 *
 * Das hatte zwei Fehler auf einmal:
 *
 * 1. Die Zeile lief durch eine Shell. databaseUrl kommt aus --url bzw.
 *    DATABASE_URL, und `$(...)` oder Backticks werden auch in doppelten
 *    Anfuehrungszeichen noch ausgefuehrt.
 * 2. `.replace(/\n/g, ' ')` machte aus der SQL EINE Zeile — und die begann
 *    nach .trim() mit `--`. psql sah also einen einzigen Kommentar und fuehrte
 *    NICHTS aus. Der psql-Pfad hat nie einen Datensatz geschrieben.
 *
 * execFile nimmt ein Argument-Feld statt einer Zeile (keine Shell), und die
 * SQL geht ueber stdin — damit bleiben die Zeilenumbrueche erhalten und die
 * Kommentare kommentieren nur ihre eigene Zeile.
 */
function runPsql(databaseUrl, sql) {
  return new Promise((resolve, reject) => {
    const child = execFile(
      'psql',
      [databaseUrl, '-v', 'ON_ERROR_STOP=1', '-f', '-'],
      (error, stdout, stderr) => {
        if (error) {
          error.stdout = stdout;
          error.stderr = stderr;
          reject(error);
          return;
        }
        resolve({ stdout, stderr });
      },
    );
    child.stdin.end(sql);
  });
}

/**
 * Einfache Anfuehrungszeichen verdoppeln — die uebliche Maskierung fuer ein
 * SQL-Zeichenkettenliteral. Mit standard_conforming_strings (seit PG 9.1
 * Vorgabe) ist ein Backslash ein gewoehnliches Zeichen, mehr braucht es nicht.
 * Bewusst NICHT ueber `psql -v`: das haette das Passwort in die
 * Prozessliste gelegt.
 */
function sqlLiteral(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}


