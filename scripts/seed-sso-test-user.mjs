function parseArgs(args) {
  const parsed = { password: null, environment: 'staging', url: null, help: false };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--password' && args[i + 1]) parsed.password = args[++i];
    else if (arg === '--env' && args[i + 1]) parsed.environment = args[++i];
    else if (arg === '--url' && args[i + 1]) parsed.url = args[++i];
    else if (arg === '--help' || arg === '-h') parsed.help = true;
  }
  return parsed;
}

